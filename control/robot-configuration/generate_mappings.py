"""Generate firmware headers and markdown tables from hexaloam_config.json."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CFG_PATH = ROOT / "control" / "robot-configuration" / "hexaloam_config.json"
HEADER_PATH = ROOT / "firmware" / "shared" / "hexaloam_joint_map.h"
DOC_PATH = ROOT / "control" / "robot-configuration" / "JOINT_MAPPING.md"


def main() -> None:
    cfg = json.loads(CFG_PATH.read_text(encoding="utf-8"))
    joints = cfg["joints"]
    links = cfg["cad_geometry"]["links"]
    servo = cfg["servo_actuator"]

    lines = [
        "#pragma once",
        "// AUTO-GENERATED by control/robot-configuration/generate_mappings.py",
        "// Source of truth: control/robot-configuration/hexaloam_config.json",
        "#include <stdint.h>",
        "",
        "namespace hexaloam {",
        "",
        f"constexpr uint8_t NUM_JOINTS = {len(joints)};",
        f"constexpr uint8_t NUM_LEGS = {cfg['robot']['legs']};",
        f"constexpr uint16_t SERVO_PWM_HZ = {servo['pwm_frequency_hz']};",
        f"constexpr uint16_t SERVO_MIN_US = {servo['min_pulse_us']};",
        f"constexpr uint16_t SERVO_NEUTRAL_US = {servo['neutral_pulse_us']};",
        f"constexpr uint16_t SERVO_MAX_US = {servo['max_pulse_us']};",
        "",
        f"constexpr float COXA_LENGTH_M = {links['coxa']['radial_length_m']}f;",
        f"constexpr float COXA_LATERAL_OFFSET_M = {links['coxa']['lateral_offset_m']}f;",
        f"constexpr float COXA_VERTICAL_RISE_M = {links['coxa']['vertical_rise_from_yaw_shaft_m']}f;",
        f"constexpr float FEMUR_LENGTH_M = {links['femur']['length_m']}f;",
        f"constexpr float TIBIA_LENGTH_M = {links['tibia']['length_m']}f;",
        f"constexpr float TIBIA_LATERAL_OFFSET_M = {links['tibia']['lateral_offset_m']}f;",
        f"constexpr float FOOT_SPHERE_RADIUS_M = {links['tibia']['foot_sphere_radius_m']}f;",
        "",
        "struct JointMapEntry {",
        "  uint8_t id;",
        "  const char* name;",
        "  uint8_t mega_pin;",
        "  char pca_board;",
        "  uint8_t pca_addr_single;",
        "  uint8_t pca_addr_dual;",
        "  uint8_t pca_channel;",
        "  int8_t direction;",
        "  float min_rad;",
        "  float max_rad;",
        "  float neutral_rad;",
        "};",
        "",
        "constexpr JointMapEntry JOINT_MAP[NUM_JOINTS] = {",
    ]
    for j in joints:
        lines.append(
            f'  {{{j["id"]}, "{j["name"]}", {j["mega_pin"]}, \'{j["pca_board"]}\', '
            f'{j["pca_addr_single_esp32"]}, {j["pca_addr_dual_esp32"]}, {j["pca_channel"]}, '
            f'{j["direction"]}, {j["min_rad"]}f, {j["max_rad"]}f, {j["neutral_rad"]}f}},'
        )
    lines.extend(["};", "", "}  // namespace hexaloam", ""])

    HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
    HEADER_PATH.write_text("\n".join(lines), encoding="utf-8")

    md = [
        "# HexaLoam Canonical 18-Servo Joint Mapping",
        "",
        "Auto-generated from [hexaloam_config.json](hexaloam_config.json).",
        "",
        "| ID | Name | Leg | Joint | Mega Pin | PCA Board | Ch | Single-ESP32 Addr | Dual-ESP32 Node/Addr | Dir | Min (rad) | Max (rad) | Neutral (rad) |",
        "|---:|---|---|---|---|---|---:|---|---|---:|---:|---:|---:|",
    ]
    for j in joints:
        md.append(
            f"| {j['id']} | `{j['name']}` | {j['leg']} | {j['joint']} | {j['mega_pin_label']} | "
            f"{j['pca_board']} | {j['pca_channel']} | `{j['pca_addr_single_esp32']}` | "
            f"{j['esp32_dual_node']} / `{j['pca_addr_dual_esp32']}` | {j['direction']} | "
            f"{j['min_rad']:.3f} | {j['max_rad']:.3f} | {j['neutral_rad']:.3f} |"
        )
    DOC_PATH.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"Generated {HEADER_PATH.relative_to(ROOT)} and {DOC_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
